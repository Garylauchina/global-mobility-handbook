#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import {
  categoryDefinitions,
  enumerateCategory,
} from "./content-tree.mjs";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");
const outputPath = path.join(repositoryRoot, "mkdocs.yml");
const checkOnly = process.argv.includes("--check");

const quote = (value) => JSON.stringify(value);

function pageTitle(markdown, fallback) {
  const frontMatter = markdown.match(/^---\n([\s\S]*?)\n---/);
  const titleInFrontMatter = frontMatter?.[1].match(/^title:\s*["']?(.+?)["']?\s*$/m);
  if (titleInFrontMatter) return titleInFrontMatter[1];

  const heading = markdown.match(/^#\s+(.+)$/m);
  return heading?.[1] ?? fallback;
}

async function buildNavigation() {
  const lines = [
    "nav:",
    `  - ${quote("首页")}: README.md`,
    `  - ${quote("按方案类型")}:`,
  ];

  for (const definition of categoryDefinitions) {
    const { directory, navigationLabel, levels } = definition;
    const tree = await enumerateCategory(repositoryRoot, definition);

    lines.push(`      - ${quote(navigationLabel)}:`);
    lines.push(`          - ${quote("类别说明")}: ${directory}/README.md`);

    for (const country of tree.countries) {
      const title = pageTitle(country.markdown, country.label);
      if (levels.length === 1) {
        lines.push(
          `          - ${quote(title)}: ${directory}/${country.slug}/README.md`,
        );
        continue;
      }

      lines.push(`          - ${quote(title)}:`);
      lines.push(
        `              - ${quote("国家说明")}: ${directory}/${country.slug}/README.md`,
      );
      for (const route of country.routes) {
        lines.push(
          `              - ${quote(route.label)}: ${directory}/${country.slug}/${route.slug}/README.md`,
        );
      }
    }
  }

  lines.push(`  - ${quote("研究与治理")}:`);
  lines.push(`      - ${quote("研究方法")}: METHODOLOGY.md`);
  lines.push(`      - ${quote("更新政策")}: UPDATE_POLICY.md`);
  lines.push(`      - ${quote("维护手册")}: MAINTENANCE.md`);
  lines.push(`      - ${quote("免责声明")}: DISCLAIMER.md`);
  lines.push(`      - ${quote("独立性声明")}: INDEPENDENCE.md`);
  lines.push(`      - ${quote("贡献指南")}: CONTRIBUTING.md`);
  lines.push(`      - ${quote("更新记录")}: CHANGELOG.md`);
  lines.push(`  - ${quote("English overview")}: README.en.md`);

  return lines.join("\n");
}

