#!/usr/bin/env node

import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");
const outputPath = path.join(repositoryRoot, "mkdocs.yml");
const checkOnly = process.argv.includes("--check");

const categories = [
  ["citizenship-by-investment", "投资入籍"],
  ["investment-permanent-residence", "投资永居"],
  ["investment-residence", "投资居留"],
  ["entrepreneur-business-residence", "创业与经营居留"],
  ["digital-nomad-remote-work", "数字游民与远程工作"],
  ["visitor-financial-remote", "访客或财力型远程工作"],
  ["passive-income-retirement", "被动收入与退休居留"],
  ["closed-paused-unverified", "停办、暂停、被替代与待核项目"],
];

const quote = (value) => JSON.stringify(value);

function pageTitle(markdown, fallback) {
  const frontMatter = markdown.match(/^---\n([\s\S]*?)\n---/);
  const titleInFrontMatter = frontMatter?.[1].match(/^title:\s*["']?(.+?)["']?\s*$/m);
  if (titleInFrontMatter) return titleInFrontMatter[1];

  const heading = markdown.match(/^#\s+(.+)$/m);
  return heading?.[1] ?? fallback;
}

function categoryLinks(markdown) {
  const links = [];
  const pattern = /^- \[([^\]]+)\]\(\.\/([^/)]+)\/(?:README\.md)?\)$/gm;
  for (const match of markdown.matchAll(pattern)) {
    links.push({ label: match[1], slug: match[2] });
  }
  return links;
}

async function buildNavigation() {
  const lines = [
    "nav:",
    `  - ${quote("首页")}: README.md`,
    `  - ${quote("按方案类型")}:`,
  ];

  for (const [directory, label] of categories) {
    const categoryReadmePath = path.join(repositoryRoot, directory, "README.md");
    const categoryReadme = await readFile(categoryReadmePath, "utf8");
    const links = categoryLinks(categoryReadme);
    const childDirectories = (await readdir(path.join(repositoryRoot, directory), {
      withFileTypes: true,
    }))
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();
    const listedDirectories = links.map(({ slug }) => slug).sort();

    if (JSON.stringify(childDirectories) !== JSON.stringify(listedDirectories)) {
      throw new Error(
        `${directory}/README.md 的国家目录清单与实际子目录不一致。请先更新类别页。`,
      );
    }

    lines.push(`      - ${quote(label)}:`);
    lines.push(`          - ${quote("类别说明")}: ${directory}/README.md`);

    for (const { label: linkedLabel, slug } of links) {
      const countryPath = path.join(repositoryRoot, directory, slug, "README.md");
      const countryMarkdown = await readFile(countryPath, "utf8");
      const title = pageTitle(countryMarkdown, linkedLabel);
      lines.push(
        `          - ${quote(title)}: ${directory}/${slug}/README.md`,
      );
    }
  }

  lines.push(`  - ${quote("研究与治理")}:`);
  lines.push(`      - ${quote("研究方法")}: METHODOLOGY.md`);
  lines.push(`      - ${quote("更新政策")}: UPDATE_POLICY.md`);
  lines.push(`      - ${quote("免责声明")}: DISCLAIMER.md`);
  lines.push(`      - ${quote("独立性声明")}: INDEPENDENCE.md`);
  lines.push(`      - ${quote("贡献指南")}: CONTRIBUTING.md`);
  lines.push(`      - ${quote("更新记录")}: CHANGELOG.md`);
  lines.push(`  - ${quote("English overview")}: README.en.md`);

  return lines.join("\n");
}

