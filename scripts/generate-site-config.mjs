const generated = await expectedConfig();

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error("mkdocs.yml 与当前目录不同步；请运行 node scripts/generate-site-config.mjs。 ");
    process.exit(1);
  }
  console.log("Site navigation is synchronized.");
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log("Generated mkdocs.yml.");
}
